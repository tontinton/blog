import * as V from '../lib/index.js';
const { Stage, VoxelGrid, Palette, NATURE, BUILD } = V;
const stage = new Stage({ look: 'daylight', camera: { yaw: 35, pitch: 35 } });
const P = new Palette({ ...NATURE, ...BUILD });
const g = new VoxelGrid(P);
V.tile(g, [-40, -30], [40, 30], { depth: 5, corner: 3 });
V.oak(g, [-32, 1, -20], { height: 14, seed: 1 });
V.oak(g, [-14, 1, -22], { height: 12, seed: 2, style: 'clumps' });
V.blossom(g, [4, 1, -22], { height: 13, seed: 3 });
V.pine(g, [20, 1, -22], { height: 20, seed: 4 });
V.palm(g, [34, 1, -20], { height: 16, seed: 5 });
V.willow(g, [-32, 1, 2], { height: 12, seed: 6 });
V.branches(g, [-16, 1, 4], { height: 12, seed: 7 });
V.bush(g, [-4, 1, 4], { radius: 3, seed: 8 });
V.rock(g, [6, 1, 4], { size: [4, 3, 3], seed: 9, moss: 'moss' });
V.mushroom(g, [12, 1, 0], { dots: 'petalWhite' });
V.reeds(g, [16, 1, 0]);
for (let i = 0; i < 8; i++) V.flower(g, [20 + (i % 4) * 2, 1, 2 + Math.floor(i / 4) * 2], { seed: i });
V.cloud(g, [0, 34, 0], { length: 20, seed: 4 });
const h = V.house(g, [-36, 1, 14], { w: 11, d: 9, h: 5, chimney: true, lit: 0.5 });
V.smoke(g, h.chimneyTop, { height: 9 });
V.fence(g, [[-22, 1, 26], [-6, 1, 26]], { every: 3 });
V.lamppost(g, [-4, 1, 22], { arm: '+x' });
V.well(g, [4, 1, 20]);
V.truss(g, [14, 1, 14], [14, 18, 14], 'metal');
V.truss(g, [14, 18, 14], [30, 18, 14], 'metal');
V.crate(g, [20, 1, 22]); V.crate(g, [22, 1, 22]); V.crate(g, [21, 3, 22]);
V.barrel(g, [27, 1, 24]);
V.scatter(g, (x, y, z, R) => V.grassTuft(g, [x, y, z], { R }), { on: ['grass'], density: 0.08 });
stage.add(g, { bake: { ao: true, light: true } });
stage.start();
